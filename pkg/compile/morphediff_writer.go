// writeSingleFile writes all content to a single file
func (w *MorphediffWriter) writeSingleFile(fileName string, contents map[string][]byte) error {
	var combined []byte

	// Add file header
	if w.AddGeneratedHeader {
		combined = append(combined, []byte(w.getGeneratedHeader())...)
	}

	// Combine all contents
	for name, content := range contents {
		combined = append(combined, []byte(fmt.Sprintf("\n-- --- %s ---\n", name))...)
		combined = append(combined, content...)
		combined = append(combined, '\n')
	}

	// Write to single file
	filePath := filepath.Join(w.OutputPath, fileName+w.FileExtension)
	return os.WriteFile(filePath, combined, 0644)
}

// Helper function to convert type names to file names
func toFileName(typeName string) string {
	// TODO: Adjust for your format's file naming conventions
	// Examples:
	// - PostgreSQL migrations: "001_add_user_table" (keep as-is or convert to snake_case)
	// - OpenAPI: "add_user_endpoint" (kebab-case)
	// - TypeScript: "UserMigration" (PascalCase) -> "user-migration" (kebab-case)

	// Default: convert to lowercase with underscores
	var result []rune
	for i, r := range typeName {
		if i > 0 && 'A' <= r && r <= 'Z' {
			result = append(result, '_')
		}
		result = append(result, r)
	}
	return strings.ToLower(string(result))
}

