package compile

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// MorphediffWriter handles writing compiled output to files in the target format
type MorphediffWriter struct {
	OutputPath string
	// Configuration with sensible defaults
	FileExtension      string
	UseMultiFile       bool // Default: true (one file per migration/change)
	CreateIndexFile    bool // Default: false (usually not needed for migrations)
	IndentSize         int  // Default: 2 or 4 depending on format
	AddGeneratedHeader bool // Default: true
}

// NewMorphediffWriter creates a new MorphediffWriter instance with sensible defaults
func NewMorphediffWriter(outputPath string) *MorphediffWriter {
	return &MorphediffWriter{
		OutputPath:         outputPath,
		FileExtension:      ".sql",
		UseMultiFile:       true,
		CreateIndexFile:    false, // Usually not needed for migrations
		IndentSize:         4,
		AddGeneratedHeader: true,
	}
}

// getGeneratedHeader returns a header comment for generated files
func (w *MorphediffWriter) getGeneratedHeader() string {
	return `-- Generated by Morphe Diff. DO NOT EDIT.
-- Source: Morphe Diff Document

`
}

// ensureDir creates a directory if it doesn't exist
func (w *MorphediffWriter) ensureDir(dir string) error {
	return os.MkdirAll(dir, 0755)
}

// writeFile writes content to a file with optional header
func (w *MorphediffWriter) writeFile(path string, content []byte) error {
	// Add generated header if enabled
	if w.AddGeneratedHeader {
		header := []byte(w.getGeneratedHeader())
		content = append(header, content...)
	}

	// Ensure directory exists
	dir := filepath.Dir(path)
	if err := w.ensureDir(dir); err != nil {
		return fmt.Errorf("failed to create directory %s: %w", dir, err)
	}

	return os.WriteFile(path, content, 0644)
}

// WriteMigration writes a migration/change file
// TODO: Adjust naming and structure for your format
// Examples:
// - PostgreSQL: WriteMigration("001_add_user_table", content) -> 001_add_user_table.sql
// - OpenAPI: WriteMigration("add_user_endpoint", content) -> add_user_endpoint.yaml
func (w *MorphediffWriter) WriteMigration(migrationName string, content []byte) error {
	// Migration name is already in snake_case format, so just add extension
	fileName := migrationName + w.FileExtension
	filePath := filepath.Join(w.OutputPath, fileName)
	return w.writeFile(filePath, content)
}

// WriteAllMigrations writes multiple migration files
func (w *MorphediffWriter) WriteAllMigrations(migrationContents map[string][]byte) error {
	if w.UseMultiFile {
		// Write each migration to a separate file
		for migrationName, content := range migrationContents {
			if err := w.WriteMigration(migrationName, content); err != nil {
				return err
			}
		}

		// Create index file if enabled (usually not needed for migrations)
		if w.CreateIndexFile {
			return w.writeMigrationIndex(migrationContents)
		}
		return nil
	}

	// Single file mode - combine all migrations
	return w.writeSingleFile("migrations", migrationContents)
}

